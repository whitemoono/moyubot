// Uses isolated data; clipboard and external links are intercepted. No feedback is sent.
const { app, BrowserWindow, clipboard, shell } = require('electron');
const fs = require('node:fs'), path = require('node:path'), assert = require('node:assert/strict');
const root = path.resolve(__dirname, '..');
const output = path.join(root, '.work', 'feedback-smoke', String(Date.now()));
fs.mkdirSync(output, { recursive: true });
app.setPath('userData', path.join(output, 'electron'));
let win, backend, renderer, copied = '', opened = [];
const delay = (ms) => new Promise((resolve) => setTimeout(resolve, ms));
const evaluate = (fn, ...args) => win.webContents.executeJavaScript(`(${fn.toString()})(...${JSON.stringify(args)})`);
const until = async (fn, label) => {
  for (let i = 0; i < 100; i++) { if (await evaluate(fn)) return; await delay(100); }
  throw Error('Timeout: ' + label);
};
const click = async (selector) => { assert.equal(await evaluate((selector) => { const el = document.querySelector(selector); if (!el) return false; el.click(); return true; }, selector), true, selector); await delay(100); };
const button = async (text) => { assert.equal(await evaluate((text) => { const el = [...document.querySelectorAll('button')].find((node) => node.textContent.trim() === text); if (!el) return false; el.click(); return true; }, text), true, text); await delay(100); };
const input = async (selector, value) => evaluate((selector, value) => {
  const element = document.querySelector(selector);
  Object.getOwnPropertyDescriptor(element.tagName === 'TEXTAREA' ? HTMLTextAreaElement.prototype : HTMLInputElement.prototype, 'value').set.call(element, value);
  element.dispatchEvent(new Event('input', { bubbles: true }));
}, selector, value);

app.whenReady().then(async () => {
  clipboard.writeText = (text) => { copied = text; };
  shell.openExternal = async (url) => { opened.push(url); };
  const { MoyuApp } = require('../apps/desktop/dist-electron/app');
  const { startRendererServer } = require('../apps/desktop/dist-electron/renderer-server');
  backend = new MoyuApp(path.join(output, 'data'), '0.1.0');
  backend.store.updateSettings({ cloud: { driver: 'mock' }, ui: { ...backend.store.getSettings().ui, appearance: 'light' } });
  backend.cloud.updateSettings(backend.store.getSettings().cloud);
  backend.store.secrets.set('cloud:instabox', 'test-private-cloud-credential');
  backend.start();
  renderer = await startRendererServer(path.join(root, 'apps/desktop/dist'));
  win = new BrowserWindow({ width: 1460, height: 950, show: false, webPreferences: { preload: path.join(root, 'apps/desktop/dist-electron/preload.js'), contextIsolation: true, nodeIntegration: false, sandbox: true } });
  backend.setWindow(win);
  await win.loadURL(renderer.url);
  win.showInactive();
  await until(() => !!document.querySelector('[aria-label="用户菜单"]'), 'bootstrap');
  const failed = await evaluate(() => window.moyu.localExec('Write-Error "feedback-smoke-error"; exit 7', 'feedback-test'));
  assert.notEqual(failed.exitCode, 0);
  const conversation = backend.store.botConversation(backend.store.getSettings().bots[0].id);
  backend.send('moyu:event', { type: 'tool_start', conversationId: conversation.id, messageId: 'm', call: { id: 'failed-command', name: 'cloud_exec', arguments: { cmd: 'curl -H "Authorization: Bearer test-private-cloud-credential" https://example.com?token=hidden' } } });
  backend.send('moyu:event', { type: 'tool_end', conversationId: conversation.id, messageId: 'm', result: { id: 'failed-command', name: 'cloud_exec', ok: false, summary: '云电脑命令连接失败', detail: 'HTTP 503', durationMs: 10 } });
  await click('[aria-label="用户菜单"]'); await button('设置'); await button('反馈与帮助');
  await until(() => !!document.querySelector('.feedback-page'), 'feedback page');
  await delay(400);
  assert.equal(await evaluate(() => document.querySelectorAll('.feedback-channel').length), 3);
  assert.equal(await evaluate(() => document.querySelector('.feedback-preview textarea').value.includes('feedback-smoke-error')), false);
  await input('[aria-label="反馈标题"]', '云电脑连接异常');
  await input('[aria-label="反馈描述"]', '点击唤醒后，终端提示连接失败。期望正常打开。');
  await click('.feedback-diagnostics__heading input');
  await until(() => document.querySelectorAll('.feedback-record').length >= 2, 'recorded errors');
  let report = await evaluate(() => document.querySelector('.feedback-preview textarea').value);
  assert.match(report, /云电脑命令连接失败/); assert.ok(!report.includes('失败命令：'));
  await click('.feedback-command-option input');
  report = await evaluate(() => document.querySelector('.feedback-preview textarea').value);
  assert.match(report, /失败命令：/); assert.match(report, /Write-Error/); assert.ok(!report.includes('test-private-cloud-credential')); assert.ok(!report.includes('?token=hidden'));
  await input('[aria-label="反馈内容预览"]', report + '\n补充：重启后仍会复现。');
  await button('复制反馈'); assert.match(copied, /补充：重启后仍会复现/);
  await button('GitHub 提交 Issue');
  assert.ok(opened.at(-1).startsWith('https://github.com/whitemoono/moyubot/issues/new?'));
  assert.ok(!opened.at(-1).includes('body=')); assert.ok(!opened.at(-1).includes('feedback-smoke-error'));
  assert.match(copied, /失败命令：/);
  await click('.feedback-channel:nth-child(1)'); assert.equal(opened.at(-1), 'https://t.me/moyubotnya');
  await click('.feedback-channel:nth-child(2)'); assert.equal(copied, '2162036353');
  await delay(500);
  fs.writeFileSync(path.join(output, 'feedback-light.png'), (await win.webContents.capturePage()).toPNG());
  const outside = await evaluate(() => [...document.querySelectorAll('.feedback-channel,.feedback-footer button,.feedback-card')].filter((element) => { const r = element.getBoundingClientRect(); return r.left < 0 || r.right > innerWidth || r.width < 20; }).length);
  assert.equal(outside, 0);
  await evaluate(async () => { const state = await window.moyu.bootstrap(); await window.moyu.saveSettings({ ui: { ...state.settings.ui, appearance: 'dark' } }); });
  await win.reload();
  await until(() => !!document.querySelector('[aria-label="用户菜单"]'), 'reload');
  await click('[aria-label="用户菜单"]'); await button('设置'); await button('反馈与帮助');
  await click('.feedback-diagnostics__heading input'); await click('.feedback-command-option input');
  await delay(400);
  fs.writeFileSync(path.join(output, 'feedback-dark.png'), (await win.webContents.capturePage()).toPNG());
  await click('[aria-label="清空报错记录"]');
  await until(() => !!document.querySelector('.feedback-empty'), 'clear');
  assert.equal((await evaluate(() => window.moyu.feedbackDiagnostics())).length, 0);
  console.log('Feedback smoke passed. Screenshots: ' + output);
}).catch((error) => { console.error(error); process.exitCode = 1; }).finally(async () => { await backend?.desktop.dispose(); backend?.dispose(); win?.destroy(); renderer?.close(); app.exit(process.exitCode || 0); });
